#!/usr/bin/env bash
# Opt-in resource limits for the comfyui service, so tulu stays usable while generating.
# Off by default. Nothing here runs unless you call it.
#
#   comfy/limits.sh on       # install the drop-in, restart comfyui (sudo)
#   comfy/limits.sh off      # remove it, restart comfyui (sudo)
#   comfy/limits.sh status   # show whether limits are on and the flags in effect
#
# What "on" applies: the flags in comfy/comfyui-args plus the systemd settings in comfy/limits.conf,
# as /etc/systemd/system/comfyui.service.d/zz-imagegen-limits.conf ("zz-" so it applies after any
# other drop-in, e.g. one from `systemctl edit`). Turning on or off restarts comfyui, which
# cancels a running generation.
set -euo pipefail
HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
DROPIN_DIR=/etc/systemd/system/comfyui.service.d
DROPIN="$DROPIN_DIR/zz-imagegen-limits.conf"
COMFY_URL="${IMAGEGEN_COMFY_URL:-http://127.0.0.1:8188}"

die() { echo "!! $*" >&2; exit 1; }

# The effective command line as systemd sees it: drop-ins applied, continuation lines joined.
effective_exec() {
  systemctl show -P ExecStart comfyui | sed -n 's/.*argv\[\]=\([^;]*\) ;.*/\1/p' | sed 's/ *$//'
}

wait_healthy() {
  echo "==> waiting for ComfyUI at $COMFY_URL (up to 90 s)"
  for _ in $(seq 1 45); do
    systemctl is-active --quiet comfyui || break
    curl -fsS -o /dev/null --max-time 2 "$COMFY_URL/system_stats" && { echo "==> ComfyUI is up."; return 0; }
    sleep 2
  done
  die "ComfyUI did not come up. Logs: journalctl -u comfyui -n 50. Turn limits off: $0 off"
}

restart() { sudo systemctl daemon-reload && sudo systemctl restart comfyui && wait_healthy; }

cmd_status() {
  if [ -f "$DROPIN" ]; then echo "Limits: ON ($DROPIN)"; else echo "Limits: off"; fi
  echo "ExecStart: $(effective_exec)"
  systemctl show -p Nice -p CPUWeight -p IOWeight comfyui | sed 's/^/  /'
}

cmd_on() {
  systemctl cat comfyui >/dev/null 2>&1 || die "no comfyui systemd service found"
  local extra base new
  extra=$( { grep -vE '^[[:space:]]*(#|$)' "$HERE/comfyui-args" || true; } | tr '\n' ' ' | sed 's/ *$//')
  # Read the base command with our drop-in out of the way, so flags never stack.
  if [ -f "$DROPIN" ]; then
    sudo mv "$DROPIN" "$DROPIN.off" && sudo systemctl daemon-reload
  fi
  base=$(effective_exec)
  [ -n "$base" ] || { [ -f "$DROPIN.off" ] && sudo mv "$DROPIN.off" "$DROPIN"; die "could not read comfyui's ExecStart"; }
  new=$(mktemp)
  {
    echo "# Generated by imagegen comfy/limits.sh. Edit comfy/limits.conf or comfy/comfyui-args, then: comfy/limits.sh on"
    cat "$HERE/limits.conf"
    if [ -n "$extra" ]; then echo "ExecStart="; echo "ExecStart=$base $extra"; fi
  } > "$new"
  echo "==> Installing $DROPIN (sudo):"; sed 's/^/    /' "$new"
  sudo mkdir -p "$DROPIN_DIR"
  sudo install -m 644 "$new" "$DROPIN"
  sudo rm -f "$DROPIN.off"; rm -f "$new"
  restart
}

cmd_off() {
  if [ ! -f "$DROPIN" ]; then echo "Limits are already off. Nothing to do."; return 0; fi
  sudo rm -f "$DROPIN"
  echo "==> Removed $DROPIN"
  restart
}

case "${1:-status}" in
  on) cmd_on ;;
  off) cmd_off ;;
  status) cmd_status ;;
  *) echo "usage: $0 on|off|status" >&2; exit 2 ;;
esac
