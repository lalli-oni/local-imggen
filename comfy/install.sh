#!/usr/bin/env bash
# Install the comfyui systemd drop-in from comfy/limits.conf + comfy/comfyui-args.
# Idempotent: rebuilds from the service's original ExecStart each time, and only restarts on change.
# Undo: comfy/install.sh --remove
set -euo pipefail
HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
DROPIN_DIR=/etc/systemd/system/comfyui.service.d
DROPIN="$DROPIN_DIR/imagegen.conf"

if [ "${1:-}" = "--remove" ]; then
  sudo rm -f "$DROPIN" && sudo systemctl daemon-reload && sudo systemctl restart comfyui
  echo "Removed $DROPIN and restarted comfyui."; exit 0
fi

# Original ExecStart from the main unit file (not from drop-ins), so re-runs don't stack flags.
unit_file=$(systemctl show -P FragmentPath comfyui)
[ -n "$unit_file" ] || { echo "!! comfyui service not found"; exit 1; }
base_exec=$(grep -m1 '^ExecStart=' "$unit_file" | cut -d= -f2-)
[ -n "$base_exec" ] || { echo "!! no ExecStart in $unit_file"; exit 1; }
extra=$(grep -vE '^[[:space:]]*(#|$)' "$HERE/comfyui-args" | tr '\n' ' ' | sed 's/ *$//')

new=$(mktemp)
{
  echo "# Generated by imagegen comfy/install.sh. Edit comfy/limits.conf or comfy/comfyui-args instead."
  cat "$HERE/limits.conf"
  echo "ExecStart="
  echo "ExecStart=$base_exec $extra"
} > "$new"

if cmp -s "$new" "$DROPIN" 2>/dev/null; then
  echo "==> comfyui drop-in unchanged."
  rm -f "$new"; exit 0
fi

echo "==> Installing $DROPIN (asks for sudo):"
cat "$new"
sudo mkdir -p "$DROPIN_DIR"
sudo install -m 644 "$new" "$DROPIN"
rm -f "$new"
sudo systemctl daemon-reload
sudo systemctl restart comfyui
sleep 3
systemctl is-active --quiet comfyui && echo "==> comfyui restarted with: $extra" \
  || { echo "!! comfyui failed to start. Logs: journalctl -u comfyui -n 50. Undo: $0 --remove"; exit 1; }
